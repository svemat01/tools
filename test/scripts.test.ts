import { describe, expect, test } from "bun:test";

import { RootCommand } from "@bomb.sh/tab";

import { patchScript } from "../src/kit/scripts.ts";
import { fixtureApp } from "./fixtures/app.ts";

function upstream(shell: string, program = "fx"): string {
  const lines: string[] = [];
  const log = console.log;
  console.log = (text: unknown) => lines.push(String(text));
  try {
    new RootCommand().setup(program, program, shell);
  } finally {
    console.log = log;
  }
  return `${lines.join("\n")}\n`;
}

describe("generated completion scripts", () => {
  const app = fixtureApp();

  test("call the program by name through the complete protocol", () => {
    for (const shell of ["zsh", "bash", "fish", "powershell"] as const) {
      expect(app.script(shell)).toMatch(/fx complete '?--'?/);
    }
  });

  test("fish and powershell are Tab's scripts unchanged", () => {
    for (const shell of ["fish", "powershell"] as const) {
      expect(app.script(shell)).toBe(upstream(shell));
    }
  });

  test("bash gets the four documented fixes and nothing else", async () => {
    const script = app.script("bash");
    expect(script).toContain("complete -o default -F __fx_complete fx\n");
    expect(script).toContain('_filedir "$filter"');
    expect(script).toContain("_filedir -d");
    expect(script).toContain('[[ "$word" == -*=* ]] && word="${word#*=}"');
    expect(script).not.toContain("compgen -f -X");

    const changed = script.split("\n").filter((line) => !upstream("bash").split("\n").includes(line));
    expect(changed).toEqual([
      '        local filter="" ext',
      '            filter="${filter:+$filter|}$ext"',
      '        _filedir "$filter"',
      "        _filedir -d",
      '    local word="$cur"',
      '    [[ "$word" == -*=* ]] && word="${word#*=}"',
      '    COMPREPLY=( $(compgen -W "${completions[*]}" -- "$word") )',
      "complete -o default -F __fx_complete fx",
    ]);

    // Still valid bash (any version).
    const check = Bun.spawnSync(["bash", "-n"], { stdin: new TextEncoder().encode(script) });
    expect(check.exitCode).toBe(0);
  });

  test("zsh gets the three documented fixes and nothing else", () => {
    const script = app.script("zsh");
    const original = upstream("zsh").split("\n");
    const changed = script.split("\n").filter((line) => !original.includes(line));
    expect(changed).toEqual([
      '    words=( "${(@)words[1,CURRENT]}" )',
      '    local -a unquoted_args=("${(@Q)args_to_quote}")',
      '    local quoted_args=("${(@q)unquoted_args}")',
      "            comp=${comp//:/\\\\:}",
    ]);
  });

  test.skipIf(!Bun.which("zsh"))("zsh accepts the patched script", () => {
    const check = Bun.spawnSync(["zsh", "-n"], {
      stdin: new TextEncoder().encode(app.script("zsh")),
    });
    expect(check.exitCode).toBe(0);
  });

  test("program names with dashes map to Tab's bash identifiers", () => {
    expect(patchScript("bash", "my-cli", upstream("bash", "my-cli"))).toContain(
      "complete -o default -F __my_cli_complete my-cli",
    );
  });

  test("a changed upstream script fails loudly instead of being half-patched", () => {
    expect(() =>
      patchScript("bash", "fx", upstream("bash").replace("compgen -d", "compgen -o dirnames")),
    ).toThrow(/generated by @bomb.sh\/tab changed/);
  });
});
